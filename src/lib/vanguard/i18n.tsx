const DICTS = { en, cs, ur };

const LanguageContext = createContext<{
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: keyof typeof en) => string;
} | null>(null);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>("en");
  useEffect(() => {
    const stored = window.localStorage.getItem("vg-lang");
    if (stored === "cs" || stored === "ur" || stored === "en") setLangState(stored);
  }, []);
  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = "ltr";
    document.documentElement.classList.toggle("lang-ur", lang === "ur");
  }, [lang]);
  const value = useMemo(() => {
    const dict = DICTS[lang];
    return {
      lang,
      setLang: (l: Lang) => {
        setLangState(l);
        window.localStorage.setItem("vg-lang", l);
      },
      t: (key: keyof typeof en) => dict[key] ?? en[key],
    };
  }, [lang]);
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function softenError(raw: string, busy: string) {
  if (/quota exceeded|RESOURCE_EXHAUSTED|Google Sheets API|register is busy|Read requests per minute/i.test(raw) || raw.length > 240) return busy;
  return raw;
}

export function useI18n() {
  const ctx = useContext(LanguageContext);
  if (!ctx) throw new Error("LanguageProvider missing");
  return ctx;
}

